export function getTranslations(lang?: string): UiTranslations {
  const code = (lang || 'pl').toLowerCase().slice(0, 2) as SupportedLangCode
  return TRANSLATIONS[code] || TRANSLATIONS.pl
}

export function useUiLanguage(defaultLang: SupportedLangCode = 'pl') {
  const [uiLang, setUiLangState] = useState<SupportedLangCode>(defaultLang)

  useEffect(() => {
    try {
      const saved = localStorage.getItem('vse_ui_lang')?.toLowerCase() as SupportedLangCode | undefined
      if (saved && TRANSLATIONS[saved]) {
        setUiLangState(saved)
      }
    } catch {
      // ignore storage errors
    }

    const onCustomLangChange = (e: Event) => {
      const custom = e as CustomEvent<SupportedLangCode>
      if (custom.detail && TRANSLATIONS[custom.detail]) {
        setUiLangState(custom.detail)
      }
    }
    window.addEventListener('vse-lang-change', onCustomLangChange)
    return () => window.removeEventListener('vse-lang-change', onCustomLangChange)
  }, [])

  const setUiLang = useCallback((next: string) => {
    const code = (next || 'pl').toLowerCase().slice(0, 2) as SupportedLangCode
    if (!TRANSLATIONS[code]) return
    setUiLangState(code)
    try {
      localStorage.setItem('vse_ui_lang', code)
      window.dispatchEvent(new CustomEvent('vse-lang-change', { detail: code }))
    } catch {
      // ignore
    }
  }, [])

  return { uiLang, setUiLang, t: getTranslations(uiLang) }
}
